import {animationUtils} from '../../../proxy.mjs';
const signLoop = 'jb2a.magic_signs.circle.02.conjuration.loop.blue';
const pulse = 'modules/animated-spell-effects-cartoon/spell-effects/cartoon/energy/energy_pulse_yellow_CIRCLE.webm';
async function teleOut(token) {
    /* eslint-disable indent */
    await new Sequence()
        .effect()
            .file('jb2a.particles.outward.blue.01.05')
            .atLocation(token)
            .filter('ColorMatrix', {saturate: -1, brightness: 2})
            .scaleToObject(1.7)
            .fadeIn(3000, {ease: 'easeInExpo'})
            .duration(5500)
        .effect()
            .file('jb2a.magic_signs.circle.02.conjuration.intro.blue')
            .atLocation(token)
            .belowTokens()
            .scaleToObject(3)
            .filter('ColorMatrix', {saturate: -0.25, brightness: 1})
            .opacity(0.8)
            .waitUntilFinished(-500)
        .effect()
            .file(signLoop)
            .atLocation(token)
            .filter('ColorMatrix', {saturate: -0.5, brightness: 1.5})
            .opacity(0.65)
            .belowTokens()
            .scaleToObject(3)
            .duration(2500)
        .effect()
            .file('jb2a.extras.tmfx.outpulse.circle.02.fast')
            .atLocation(token)
            .opacity(0.5)
            .scaleToObject(3)
            .duration(2500)
        .animation()
            .on(token)
            .delay(2000)
            .opacity(0)
        .effect()
            .copySprite(token)
            .atLocation(token)
            .scaleToObject(1.1)
            .fadeIn(2000, {ease: 'easeInExpo'})
            .filter('ColorMatrix', {saturate: -1, brightness: 10})
            .filter('Blur', {blurX: 5, blurY: 10})
            .animateProperty('sprite', 'scale.x', {from: 0.5, to: 0, duration: 500, delay: 2500, ease: 'easeOutElastic'})
            .animateProperty('spriteContainer', 'position.y', {from: 0, to: -1000, duration: 500, delay: 2500, ease: 'easeOutCubic'})
            .fadeOut(100)
            .duration(3000)
            .attachTo(token, {bindAlpha: false})
            .waitUntilFinished(-700)
        .play();
    new Sequence()
        .effect()
            .playIf(animationUtils.aseCheck())
            .file(pulse)
            .atLocation(token)
            .scaleToObject(4)
            .filter('ColorMatrix', {saturate: -1, hue: 160, brightness: 2})
        .effect()
            .file(signLoop)
            .atLocation(token)
            .filter('ColorMatrix', {saturate: -1, brightness: 0})
            .opacity(0.3)
            .fadeOut(10000, {ease: 'easeOutQuint'})
            .belowTokens()
            .scaleToObject(3)
            .duration(20000)
        .play();
    /* eslint-enable indent */
}
async function teleIn(token) {
    /* eslint-disable indent */
    new Sequence()
        .effect()
            .copySprite(token)
            .atLocation(token)
            .scaleToObject(1.1)
            .filter('ColorMatrix', {saturate: -1, brightness: 10})
            .filter('Blur', {blurX: 5, blurY: 10})
            .animateProperty('spriteContainer', 'position.y', {from: -1000, to: 0, duration: 500, ease: 'easeOutCubic'})
            .animateProperty('sprite', 'scale.x', {from: 0.5, to: 0, duration: 500, ease: 'easeOutElastic'})
            .fadeOut(100)
            .duration(500)
            .attachTo(token, {bindAlpha: false})
            .waitUntilFinished(-300)
        .effect()
            .playIf(animationUtils.aseCheck())
            .file(pulse)
            .atLocation(token)
            .scaleToObject(4)
            .filter('ColorMatrix', {saturate: -1, hue: 160, brightness: 2})
        .effect()
            .file('jb2a.particles.outward.blue.01.03')
            .atLocation(token)
            .fadeIn(250, {ease: 'easeOutQuint'})
            .scaleIn(0, 200, {ease: 'easeOutCubic'})
            .fadeOut(5000, {ease: 'easeOutQuint'})
            .filter('ColorMatrix', {saturate: -1, brightness: 2})
            .scaleToObject(5)
            .duration(10000)
        .effect()
            .copySprite(token)
            .atLocation(token)
            .scaleToObject(1.1)
            .fadeOut(1000, {ease: 'easeInExpo'})
            .filter('ColorMatrix', {saturate: -1, brightness: 10})
            .filter('Blur', {blurX: 5, blurY: 10})
            .scaleIn(0, 500, {ease: 'easeOutCubic'})
            .duration(1200)
            .attachTo(token, {bindAlpha: false})
        .animation()
            .on(token)
            .opacity(1)
        .effect()
            .file(signLoop)
            .atLocation(token)
            .filter('ColorMatrix', {saturate: -0.5, brightness: 1.5})
            .opacity(0.65)
            .belowTokens()
            .scaleToObject(3)
            .fadeOut(4000)
            .duration(5000)
        .play();
    /* eslint-enable indent */
}
export const teleportSpell = {
    name: 'CHRISPREMADES.Animations.TeleportSpell',
    macros: {
        preAnimation: teleOut,
        postAnimation: teleIn
    },
    inputs: ['token', 'options'],
    requirements: ['jb2a_patreon'],
    category: 'spell'
};
