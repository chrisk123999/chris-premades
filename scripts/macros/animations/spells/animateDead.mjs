import {animationUtils} from '../../../proxy.mjs';
import {pickFile} from '../generic/spellParts.mjs';
import {prePlace, preRemove} from '../generic/summons.mjs';
// A necromantic circle charges, bursts, and the corpse rises.
async function postPlace(summon, location, token) {
    const hasAse = animationUtils.aseCheck();
    /* eslint-disable indent */
    await new Sequence()
        .wait(50)
        .effect()
            .atLocation(token)
            .file(pickFile('jb2a.magic_signs.circle.02.necromancy.complete.green', 'jb2a.magic_signs.circle.02.necromancy.complete.dark_green'))
            .size(1.25, {gridUnits: true})
            .belowTokens()
            .fadeOut(2000)
            .zIndex(0)
        .effect()
            .delay(2250)
            .atLocation(token)
            .file(pickFile('jb2a.magic_signs.circle.02.necromancy.loop.green', 'jb2a.magic_signs.circle.02.necromancy.loop.dark_green'))
            .size(1.25, {gridUnits: true})
            .belowTokens()
            .zIndex(1)
            .duration(500)
            .playbackRate(2)
            .fadeIn(200, {ease: 'easeOutCirc'})
            .fadeOut(300, {ease: 'linear'})
        .effect()
            .file('animated-spell-effects-cartoon.electricity.ball.06')
            .delay(2250)
            .atLocation(token)
            .duration(1500)
            .fadeOut(1000)
            .size(1.75, {gridUnits: true})
            .randomRotation()
            .filter('ColorMatrix', {saturate: -1, brightness: 0})
            .zIndex(1)
            .playIf(hasAse)
        .effect()
            .delay(2250)
            .file(pickFile('jb2a.cast_generic.01.dark_purple.0', 'jb2a.cast_generic.02.blue.0'))
            .atLocation(token)
            .size(1.5, {gridUnits: true})
            .opacity(0.8)
            .playbackRate(2)
            .zIndex(2)
            .waitUntilFinished(-200)
        .effect()
            .delay(200)
            .file('animated-spell-effects-cartoon.electricity.04')
            .atLocation(token, {offset: {y: -0.4}, gridUnits: true})
            .size(1.5, {gridUnits: true})
            .playbackRate(1.5)
            .filter('ColorMatrix', {saturate: -1, brightness: 0})
            .mirrorY()
            .playIf(hasAse)
        .effect()
            .file('animated-spell-effects-cartoon.electricity.discharge.06')
            .atLocation(token)
            .size(2.25, {gridUnits: true})
            .filter('ColorMatrix', {saturate: -1, brightness: 0})
            .playbackRate(0.8)
            .fadeOut(500)
            .zIndex(2)
            .playIf(hasAse)
        .effect()
            .file(pickFile('jb2a.impact.dark.01.red', 'jb2a.impact.ground_crack.blue.01'))
            .atLocation(token)
            .size(2.5, {gridUnits: true})
            .randomizeMirrorX()
            .randomizeMirrorY()
        .effect()
            .file(pickFile('jb2a.liquid.splash.red', 'jb2a.liquid.splash.blue'))
            .atLocation(token)
            .size(1.65, {gridUnits: true})
            .belowTokens()
            .zIndex(0.1)
        .effect()
            .delay(250)
            .file('animated-spell-effects-cartoon.water.117')
            .atLocation(token)
            .size(1.3, {gridUnits: true})
            .belowTokens()
            .fadeOut(1000)
            .randomRotation()
            .loopOptions({loops: 1})
            .filter('ColorMatrix', {hue: -5, saturate: 1, brightness: 0.6})
            .zIndex(0.2)
            .playIf(hasAse)
        .animation()
            .on(token)
            .opacity(1)
            .fadeIn(500)
        .effect()
            .file(pickFile('jb2a.fireflies.many.02.green', 'jb2a.fireflies.many.01.yellow'))
            .atLocation(token)
            .size(1.25, {gridUnits: true})
            .duration(3000)
            .fadeIn(500)
            .fadeOut(1000)
            .scaleIn(0, 500, {ease: 'easeOutCubic'})
            .randomRotation()
            .zIndex(3)
        .effect()
            .delay(250)
            .file(pickFile('jb2a.static_electricity.03.dark_purple', 'jb2a.static_electricity.03.blue'))
            .atLocation(token)
            .size(1.25, {gridUnits: true})
            .belowTokens()
            .opacity(0.75)
            .playbackRate(4)
            .fadeOut(1000)
            .randomRotation()
            .repeats(5, 1000, 1500)
            .zIndex(0.3)
        .play();
    /* eslint-enable indent */
}
export const animateDeadSummon = {
    name: 'CHRISPREMADES.Animations.AnimateDeadSummon',
    macros: {
        prePlace,
        postPlace,
        preRemove
    },
    inputs: ['summon', 'location', 'token'],
    requirements: ['JB2A_DnD5e'],
    category: 'spell',
    get credits() { return [animationUtils.getCredits('eskie')]; }
};
